#!/usr/bin/env python3
"""Writes gl_pspexp_procs.h: every GLAPI/GLEXT function of gl_pspexp.c by
name, plus the extension-suffixed names programs ask for, for
glXGetProcAddress and SDL_GL_GetProcAddress. Run after adding a function."""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "gl_pspexp.c")).read()
names = sorted(set(re.findall(r"^GL(?:API|EXT)\([^,]+,\s*(gl\w+)\s*,", src, re.M)))
aliases = {
    "ARB": ["glGenBuffers", "glBindBuffer", "glBufferData", "glBufferSubData", "glDeleteBuffers", "glMapBuffer",
            "glUnmapBuffer", "glIsBuffer", "glGetBufferParameteriv", "glActiveTexture", "glClientActiveTexture",
            "glMultiTexCoord2f", "glMultiTexCoord2fv", "glMultiTexCoord2d", "glMultiTexCoord2i", "glMultiTexCoord4f",
            "glPointParameterf", "glPointParameterfv", "glLoadTransposeMatrixf", "glMultTransposeMatrixf",
            "glLoadTransposeMatrixd", "glMultTransposeMatrixd", "glCompressedTexImage2D"],
    "EXT": ["glDrawRangeElements", "glBlendEquation", "glBlendFuncSeparate", "glBlendColor", "glGenerateMipmap",
            "glMultiDrawArrays", "glPointParameterf", "glPointParameterfv"],
}
out = ["/* Generated by gen-gl-procs.py from gl_pspexp.c: do not edit. */"]
out.append("static const struct { const char *name; void *fn; } GL_PROCS[] = {")
for n in names:
    out.append('    { "%s", (void *)(uintptr_t)&GLFN(%s) },' % (n, n))
for suffix, fns in aliases.items():
    for n in fns:
        assert n in names, n
        out.append('    { "%s%s", (void *)(uintptr_t)&GLFN(%s) },' % (n, suffix, n))
out.append("};")
text = "\n".join(out) + "\n"
path = os.path.join(here, "gl_pspexp_procs.h")
if sys.argv[1:] == ["--check"]:   # the tests: is the table the file's?
    sys.exit(0 if open(path).read() == text else "gl_pspexp_procs.h is out of date: run gen-gl-procs.py")
open(path, "w").write(text)
print(len(names), "functions")
