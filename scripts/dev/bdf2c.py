#!/usr/bin/env python3
"""BDF bitmap fonts -> C glyph tables for pspexp-term's terminal fonts.

    scripts/dev/bdf2c.py OUT.c NAME=CELLWxCELLH=FILE.bdf ...

Each font becomes rows of one byte per pixel row (bit 7 = leftmost pixel,
cells up to 8 wide), for ASCII 32..126 and Latin-1 160..255 (191 glyphs,
missing ones blank), placed on the cell by the BDF's bounding boxes against
the font ascent. The C file is committed; rerun this when a font changes.
"""
import sys

import unicodedata

CODES = list(range(32, 127)) + list(range(160, 256))
FALLBACK = {0xdf: "s", 0xc6: "A", 0xe6: "a", 0xd8: "O", 0xf8: "o", 0xde: "P", 0xfe: "p", 0xd0: "D", 0xf0: "d",
            0xa3: "L", 0xa9: "c", 0xae: "r", 0xb0: "o", 0xb1: "+", 0xb7: ".", 0xd7: "x", 0xf7: "/", 0xa2: "c",
            0xa5: "Y", 0xa7: "S", 0xab: "<", 0xbb: ">", 0xa1: "!", 0xbf: "?", 0xb5: "u", 0xaa: "a", 0xba: "o"}

def load(path, cw, ch):
    ascent, glyphs, cur = None, {}, None
    with open(path, encoding="latin-1") as f:
        lines = f.read().splitlines()
    i = 0
    while i < len(lines):
        t = lines[i].split()
        if not t:
            i += 1; continue
        if t[0] == "FONT_ASCENT": ascent = int(t[1])
        elif t[0] == "STARTCHAR": cur = {"enc": None}
        elif t[0] == "ENCODING": cur["enc"] = int(t[1])
        elif t[0] == "BBX": cur["bbx"] = tuple(int(v) for v in t[1:5])
        elif t[0] == "BITMAP":
            w, h, xo, yo = cur["bbx"]
            rows = [int(lines[i + 1 + k], 16) for k in range(h)]
            nbytes = (len(lines[i + 1]) if h else 2) * 4
            cur["rows"], cur["nbits"] = rows, nbytes
            i += h
        elif t[0] == "ENDCHAR" and cur and cur["enc"] is not None:
            glyphs[cur["enc"]] = cur
        i += 1
    out = []
    for c in CODES:
        cell = [0] * ch
        g = glyphs.get(c)
        if g:
            w, h, xo, yo = g["bbx"]
            top = ascent - (yo + h)
            for k, bits in enumerate(g["rows"]):
                y = top + k
                if not 0 <= y < ch: continue
                for x in range(w):
                    if bits >> (g["nbits"] - 1 - x) & 1:
                        px = xo + x
                        if 0 <= px < cw: cell[y] |= 0x80 >> px
        out.append(cell)
    # a Latin-1 glyph the font leaves blank (Spleen 5x8 has placeholders):
    # its base letter (e for e-acute) or a look-alike
    idx = {c: i for i, c in enumerate(CODES)}
    for c in range(161, 256):
        cell = out[idx[c]]
        if any(cell): continue
        base = FALLBACK.get(c)
        if base is None:
            d = unicodedata.normalize("NFD", chr(c))[0]
            base = d if 32 <= ord(d) < 127 else "?"
        out[idx[c]] = list(out[idx[ord(base)]])
    return out

def main():
    out, specs = sys.argv[1], sys.argv[2:]
    with open(out, "w") as f:
        f.write("/* Generated by scripts/dev/bdf2c.py from the Spleen fonts (BSD-2-Clause,\n"
                " * (c) Frederic Cambus, https://github.com/fcambus/spleen): do not edit.\n"
                " * Glyphs for ASCII 32..126 then Latin-1 160..255, one byte per row. */\n"
                "#include \"term_fonts.h\"\n\n")
        names = []
        for spec in specs:
            name, size, path = spec.split("=", 2)
            cw, ch = (int(v) for v in size.split("x"))
            cells = load(path, cw, ch)
            f.write("static const uint8_t %s_bits[] = {\n" % name)
            for c, cell in zip(CODES, cells):
                f.write("    " + ",".join("0x%02x" % b for b in cell) + ",  /* %d */\n" % c)
            f.write("};\n\n")
            names.append((name, cw, ch))
        f.write("const TermFont TERM_FONTS[] = {\n")
        for name, cw, ch in names:
            f.write("    { \"%dx%d\", %d, %d, %s_bits },\n" % (cw, ch, cw, ch, name))
        f.write("};\nconst int TERM_FONT_COUNT = %d;\n" % len(names))

main()
