#!/bin/sh
# Mirrors the Stratagus `pspexp` branch (on top of `psp`) into
# compatibility/stratagus/stratagus-pspexp.patch, the same way the WarCraft
# project keeps psp/*.patch as a backup of untracked upstream clones.
set -e
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
TREE="${STRATAGUS_TREE:-$ROOT/../WarCraft/upstream/stratagus}"
OUT="$ROOT/compatibility/stratagus/stratagus-pspexp.patch"
BASE="$(git -C "$TREE" rev-parse --short psp)"
{
	echo "# PSPExp renderer backend for Stratagus."
	echo "# Apply to the WarCraft project's stratagus clone at commit $BASE (branch psp)."
	echo "# Generated by scripts/dev/export-stratagus-patch.sh"
	git -C "$TREE" diff psp -- . ':(exclude)third-party'
} > "$OUT"
# untracked new files are appended as diffs against /dev/null
for f in src/include/pspexp_video.h src/video/pspexp_video.cpp; do
	if ! git -C "$TREE" ls-files --error-unmatch "$f" >/dev/null 2>&1; then
		( cd "$TREE" && git diff --no-index /dev/null "$f" >> "$OUT" ) || true
	fi
done
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
