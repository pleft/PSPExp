#!/bin/sh
# Onion Omega2 / Omega2+ (MT7688, MIPS32r2 little-endian, no FPU, OpenWrt)
# host build, cross-compiled on this machine with Zig: static soft-float
# musl binaries that run on the Omega with nothing installed.
#
#   brew install zig        (or any Zig >= 0.13 on PATH)
#   scripts/omega/build.sh           bench + sprite demo
#   scripts/omega/build.sh doom      also Chocolate Doom with sdl-pspexp built in
#   scripts/omega/build.sh tyrian    also OpenTyrian (../tyrian/opentyrian) with sdl-pspexp
#   scripts/omega/build.sh cavestory also Cave Story's NXEngine-evo with sdl-pspexp
#   scripts/omega/build.sh jazz      also Jazz Jackrabbit's OpenJazz with sdl-pspexp
#   scripts/omega/build.sh retro     pspexp-retro with a libretro core linked in (CORE=fceumm:
#                                    ../retro/libretro-fceumm) -> bin/pspexp-retro-<core>
#                                    built in (uses the doom build's static SDL2)
#   scp build/omega/bin/* root@omega:/tmp/    (or the SD card)
#   Doom: put freedoom1.wad in /mnt/mmcblk0p1/doom/ and run doom.sh on the Omega
#
# Builds libusb 1.0 from source, then pspexp-bench, pspexp-sprite-demo, pspexp-term and pspexp-ms.
# "doom" adds a headless static SDL2, SDL2_mixer (WAV only) and SDL2_net,
# and Chocolate Doom linked with the SDL layer: OpenWrt has no usable
# LD_PRELOAD route for a static program and Zig's linker has no --wrap, so
# the game and SDL_mixer are compiled with -include pspexp_sdl_rename.h,
# which renames every hooked SDL call to the shim's pspexp_<fn>.
set -e
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
# Other targets reuse this script (scripts/gameshell/build.sh): ZIG_TARGET /
# ZIG_CPU / CROSS_NAME / CROSS_HOST select the architecture and output dir.
ZIG_TARGET="${ZIG_TARGET:-mipsel-linux-musleabi}"
ZIG_CPU="${ZIG_CPU:-mips32r2}"
CROSS_NAME="${CROSS_NAME:-omega}"
CROSS_HOST="${CROSS_HOST:-mipsel-linux-musl}"
CROSS_PROC="${CROSS_PROC:-mipsel}"
OUT="$ROOT/build/$CROSS_NAME"
LIBUSB_VER="${LIBUSB_VER:-1.0.29}"
command -v zig >/dev/null || { echo "zig not found (brew install zig)" >&2; exit 1; }
mkdir -p "$OUT/src" "$OUT/prefix" "$OUT/bin" "$ROOT/build/zig-cache"

# compiler wrappers: one path each, as autotools and CMake want
for t in cc cxx ar ranlib; do
	case $t in
		cc) cmd="zig cc -target $ZIG_TARGET -mcpu=$ZIG_CPU" ;;
		cxx) cmd="zig c++ -target $ZIG_TARGET -mcpu=$ZIG_CPU" ;;
		ar) cmd='zig ar' ;;
		ranlib) cmd='zig ranlib' ;;
	esac
	cat > "$OUT/z$t" <<W
#!/bin/sh
export ZIG_GLOBAL_CACHE_DIR="$ROOT/build/zig-cache" ZIG_LOCAL_CACHE_DIR="$ROOT/build/zig-cache"
exec $cmd "\$@"
W
	chmod +x "$OUT/z$t"
done

# libusb (static, no udev)
if [ ! -f "$OUT/prefix/lib/libusb-1.0.a" ]; then
	cd "$OUT/src"
	[ -d "libusb-$LIBUSB_VER" ] || curl -sL "https://github.com/libusb/libusb/releases/download/v$LIBUSB_VER/libusb-$LIBUSB_VER.tar.bz2" | tar xjf -
	cd "libusb-$LIBUSB_VER"
	./configure --host="$CROSS_HOST" --prefix="$OUT/prefix" --disable-udev --enable-static --disable-shared \
		CC="$OUT/zcc" AR="$OUT/zar" RANLIB="$OUT/zranlib" >"$OUT/libusb-configure.log" 2>&1
	make -j8 install >"$OUT/libusb-make.log" 2>&1
fi

# PSPExp host tools
cat > "$OUT/toolchain.cmake" <<T
set(CMAKE_SYSTEM_NAME Linux)
set(CMAKE_SYSTEM_PROCESSOR $CROSS_PROC)
set(CMAKE_C_COMPILER "$OUT/zcc")
set(CMAKE_CXX_COMPILER "$OUT/zcxx")
set(CMAKE_AR "$OUT/zar")
set(CMAKE_RANLIB "$OUT/zranlib")
set(CMAKE_FIND_ROOT_PATH "$OUT/prefix")
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_EXE_LINKER_FLAGS_INIT "-static -s")
T
PKG_CONFIG_LIBDIR="$OUT/prefix/lib/pkgconfig" PKG_CONFIG_SYSROOT_DIR= \
cmake -S "$ROOT" -B "$OUT/cmake" -DCMAKE_TOOLCHAIN_FILE="$OUT/toolchain.cmake" -DCMAKE_BUILD_TYPE=Release \
	-DPSPEXP_BUILD_TESTS=OFF -DPSPEXP_BUILD_SDL=OFF >/dev/null
PKG_CONFIG_LIBDIR="$OUT/prefix/lib/pkgconfig" cmake --build "$OUT/cmake" -j8 --target pspexp-bench pspexp-sprite-demo pspexp-term pspexp-ms
cp "$OUT/cmake/pspexp-bench" "$OUT/cmake/pspexp-sprite-demo" "$OUT/cmake/pspexp-term" "$OUT/cmake/pspexp-ms" "$OUT/bin/"
cp "$ROOT/scripts/board/pspexp-exec" "$ROOT/scripts/omega/pspexp-term.init" "$OUT/bin/"
"$OUT/zcc" --version >/dev/null 2>&1 || true

if [ "$1" = "doom" ]; then
	P="$OUT/prefix" T="$OUT/toolchain.cmake"
	SDL_VER=2.30.12 MIX_VER=2.8.1 NET_VER=2.2.0 DOOM_TAG=chocolate-doom-3.1.1
	fetch() { [ -d "$OUT/src/$2" ] || curl -sL "$1" | tar -C "$OUT/src" -xzf -; }
	# the rename header: one #define per hooked function of the shim
	REN="$OUT/pspexp_sdl_rename.h"
	{
		echo "/* generated by scripts/omega/build.sh: route hooked SDL calls to sdl-pspexp */"
		echo "#ifndef PSPEXP_SDL_RENAME_H"
		echo "#define PSPEXP_SDL_RENAME_H"
		grep "^HOOK(" "$ROOT/compatibility/sdl-pspexp/sdl_pspexp.c" | sed -E 's/^HOOK\([^,]+, *([A-Za-z_]+),.*/#define \1 pspexp_\1/'
		echo "#endif"
	} > "$REN"
	fetch "https://github.com/libsdl-org/SDL/releases/download/release-$SDL_VER/SDL2-$SDL_VER.tar.gz" "SDL2-$SDL_VER"
	fetch "https://github.com/libsdl-org/SDL_mixer/releases/download/release-$MIX_VER/SDL2_mixer-$MIX_VER.tar.gz" "SDL2_mixer-$MIX_VER"
	fetch "https://github.com/libsdl-org/SDL_net/releases/download/release-$NET_VER/SDL2_net-$NET_VER.tar.gz" "SDL2_net-$NET_VER"
	[ -d "$OUT/src/chocolate-doom" ] || git clone -q --depth 1 --branch "$DOOM_TAG" https://github.com/chocolate-doom/chocolate-doom.git "$OUT/src/chocolate-doom"
	if [ ! -f "$P/lib/libSDL2.a" ]; then
		# a static program needs no dynamic-API jump table (SDL resolves it with
		# dlsym, which crashes in Zig's static musl); SDL wants the header edited
		DYN="$OUT/src/SDL2-$SDL_VER/src/dynapi/SDL_dynapi.h"
		rm -rf "$OUT/src/SDL2-$SDL_VER/build"
		grep -q "PSPEXP: static" "$DYN" || sed -i.orig 's|^#ifndef SDL_DYNAMIC_API$|#define SDL_DYNAMIC_API 0 /* PSPEXP: static */\n#ifndef SDL_DYNAMIC_API|' "$DYN"
		cmake -S "$OUT/src/SDL2-$SDL_VER" -B "$OUT/src/SDL2-$SDL_VER/build" -DCMAKE_TOOLCHAIN_FILE="$T" -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX="$P" \
			-DSDL_SHARED=OFF -DSDL_STATIC=ON -DSDL_TEST=OFF -DSDL_X11=OFF -DSDL_WAYLAND=OFF -DSDL_KMSDRM=OFF -DSDL_OPENGL=OFF -DSDL_OPENGLES=OFF \
			-DSDL_VULKAN=OFF -DSDL_DIRECTFB=OFF -DSDL_RPI=OFF -DSDL_VIVANTE=OFF -DSDL_ALSA=OFF -DSDL_PULSEAUDIO=OFF -DSDL_PIPEWIRE=OFF \
			-DSDL_JACK=OFF -DSDL_SNDIO=OFF -DSDL_ESD=OFF -DSDL_ARTS=OFF -DSDL_NAS=OFF -DSDL_OSS=OFF -DSDL_LIBSAMPLERATE=OFF -DSDL_HIDAPI=OFF \
			-DSDL_LIBUDEV=OFF -DSDL_DBUS=OFF -DSDL_IBUS=OFF -DSDL_SYSTEM_ICONV=OFF -DSDL_OFFSCREEN=ON -DSDL_DUMMYVIDEO=ON -DSDL_DUMMYAUDIO=ON \
			-DSDL_DISKAUDIO=OFF -DSDL_LOADSO=OFF -DHAVE_DLOPEN_IN_LIBC=OFF -DHAVE_DLOPEN_IN_LIBDL=OFF >"$OUT/sdl2.log" 2>&1
		cmake --build "$OUT/src/SDL2-$SDL_VER/build" -j8 >>"$OUT/sdl2.log" 2>&1 || { grep -m5 "error:" "$OUT/sdl2.log"; exit 1; }
		cmake --install "$OUT/src/SDL2-$SDL_VER/build" >>"$OUT/sdl2.log" 2>&1
	fi
	# SDL_mixer calls SDL_OpenAudioDevice: compiled with the rename header too
	rm -rf "$OUT/src/SDL2_mixer-$MIX_VER/build"
	cmake -S "$OUT/src/SDL2_mixer-$MIX_VER" -B "$OUT/src/SDL2_mixer-$MIX_VER/build" -DCMAKE_TOOLCHAIN_FILE="$T" -DCMAKE_BUILD_TYPE=Release \
		-DCMAKE_INSTALL_PREFIX="$P" -DCMAKE_PREFIX_PATH="$P" -DBUILD_SHARED_LIBS=OFF "-DCMAKE_C_FLAGS=-include $REN" \
		-DSDL2MIXER_VENDORED=OFF -DSDL2MIXER_SAMPLES=OFF -DSDL2MIXER_CMD=OFF -DSDL2MIXER_FLAC=OFF -DSDL2MIXER_GME=OFF -DSDL2MIXER_MOD=OFF \
		-DSDL2MIXER_MIDI=OFF -DSDL2MIXER_MP3=OFF -DSDL2MIXER_OPUS=OFF -DSDL2MIXER_VORBIS=OFF -DSDL2MIXER_WAVPACK=OFF -DSDL2MIXER_WAVE=ON \
		-DSDL2MIXER_AIFF=OFF -DSDL2MIXER_VOC=OFF >"$OUT/mixer.log" 2>&1
	cmake --build "$OUT/src/SDL2_mixer-$MIX_VER/build" -j8 >>"$OUT/mixer.log" 2>&1
	cmake --install "$OUT/src/SDL2_mixer-$MIX_VER/build" >>"$OUT/mixer.log" 2>&1
	if [ ! -f "$P/lib/libSDL2_net.a" ]; then
		cmake -S "$OUT/src/SDL2_net-$NET_VER" -B "$OUT/src/SDL2_net-$NET_VER/build" -DCMAKE_TOOLCHAIN_FILE="$T" -DCMAKE_BUILD_TYPE=Release \
			-DCMAKE_INSTALL_PREFIX="$P" -DCMAKE_PREFIX_PATH="$P" -DBUILD_SHARED_LIBS=OFF -DSDL2NET_SAMPLES=OFF >"$OUT/net.log" 2>&1
		cmake --build "$OUT/src/SDL2_net-$NET_VER/build" -j8 >>"$OUT/net.log" 2>&1
		cmake --install "$OUT/src/SDL2_net-$NET_VER/build" >>"$OUT/net.log" 2>&1
	fi
	# PSPExp libraries and the shim (compiled WITHOUT the rename header)
	PKG_CONFIG_LIBDIR="$P/lib/pkgconfig" cmake --build "$OUT/cmake" -j8 --target pspexp pspexp_runtime pspexp_null pspexp_tcp pspexp_usb >/dev/null
	"$OUT/zcc" -O2 -c -DPSPEXP_STATIC_RENAME -DPSPEXP_HAVE_USB -DPSPEXP_NO_SDL_EXECUTOR -D_REENTRANT -I"$P/include/SDL2" -I"$P/include" \
		"$ROOT/compatibility/sdl-pspexp/sdl_pspexp.c" -o "$OUT/sdl_pspexp_static.o"
	C="$OUT/cmake"
	LIBS="$OUT/sdl_pspexp_static.o $C/libpspexp_usb.a $C/libpspexp_tcp.a $C/libpspexp_null.a $C/libpspexp.a $C/libpspexp_runtime.a $C/libpspexp_protocol.a $P/lib/libusb-1.0.a"
	rm -rf "$OUT/src/chocolate-doom/build"
	cmake -S "$OUT/src/chocolate-doom" -B "$OUT/src/chocolate-doom/build" -DCMAKE_TOOLCHAIN_FILE="$T" -DCMAKE_BUILD_TYPE=Release \
		-DCMAKE_PREFIX_PATH="$P" -DCMAKE_FIND_PACKAGE_PREFER_CONFIG=OFF -DCMAKE_DISABLE_FIND_PACKAGE_PNG=ON \
		-DCMAKE_DISABLE_FIND_PACKAGE_SampleRate=ON -DCMAKE_DISABLE_FIND_PACKAGE_FluidSynth=ON \
		"-DCMAKE_C_FLAGS=-include $REN" "-DCMAKE_EXE_LINKER_FLAGS=-static" "-DCMAKE_C_STANDARD_LIBRARIES=$LIBS" >"$OUT/doom.log" 2>&1 \
		|| { grep -A8 "CMake Error" "$OUT/doom.log" | head -30; exit 1; }
	cmake --build "$OUT/src/chocolate-doom/build" -j8 --target chocolate-doom >>"$OUT/doom.log" 2>&1 || { tail -30 "$OUT/doom.log"; exit 1; }
	# unstripped (Zig cannot strip MIPS ELF): crash addresses map with nm -n
	cp "$OUT/src/chocolate-doom/build/src/chocolate-doom" "$OUT/bin/chocolate-doom"
	cp "$ROOT/scripts/omega/doom.sh" "$OUT/bin/doom.sh"
fi
# The SDL layer linked into a static program: every SDL call the layer hooks
# is renamed to its pspexp_ twin (a header every source includes: Zig's linker
# has no --wrap). Sets REN (the header) and LIBS (the layer and PSPExp).
shim_static() {
	REN="$OUT/pspexp_sdl_rename.h"
	{
		echo "/* generated by scripts/omega/build.sh: route hooked SDL calls to sdl-pspexp */"
		echo "#ifndef PSPEXP_SDL_RENAME_H"
		echo "#define PSPEXP_SDL_RENAME_H"
		grep "^HOOK(" "$ROOT/compatibility/sdl-pspexp/sdl_pspexp.c" | sed -E 's/^HOOK\([^,]+, *([A-Za-z_]+),.*/#define \1 pspexp_\1/'
		echo "#endif"
	} > "$REN"
	# the SDL layer as it is now (the doom build may be older)
	PKG_CONFIG_LIBDIR="$P/lib/pkgconfig" cmake --build "$OUT/cmake" -j8 --target pspexp pspexp_runtime pspexp_null pspexp_tcp pspexp_usb >/dev/null
	"$OUT/zcc" -O2 -c -DPSPEXP_STATIC_RENAME -DPSPEXP_HAVE_USB -DPSPEXP_NO_SDL_EXECUTOR -D_REENTRANT -I"$P/include/SDL2" -I"$P/include" \
		"$ROOT/compatibility/sdl-pspexp/sdl_pspexp.c" -o "$OUT/sdl_pspexp_static.o"
	C="$OUT/cmake"
	LIBS="$OUT/sdl_pspexp_static.o $C/libpspexp_usb.a $C/libpspexp_tcp.a $C/libpspexp_null.a $C/libpspexp.a $C/libpspexp_runtime.a $C/libpspexp_protocol.a $P/lib/libusb-1.0.a"
}

if [ "$1" = "retro" ]; then
	# pspexp-retro with one libretro core linked in, per core: the Omega's
	# static musl cannot dlopen. CORE=fceumm (NES) is the default; its source
	# in ../retro/libretro-<core> (git clone https://github.com/libretro/libretro-fceumm).
	P="$OUT/prefix"
	[ -f "$P/lib/libSDL2.a" ] || "$ROOT/scripts/omega/build.sh" doom
	CORE="${CORE:-fceumm}"
	SRC="$ROOT/../retro/libretro-$CORE"
	[ -f "$SRC/Makefile.libretro" ] || [ -f "$SRC/Makefile" ] || { echo "core source not found in $SRC" >&2; exit 1; }
	shim_static
	W="$OUT/src/libretro-$CORE"
	rm -rf "$W"; mkdir -p "$W"
	{ COPYFILE_DISABLE=1 tar --no-xattrs -C "$SRC" --exclude .git -cf - . ; } 2>/dev/null | tar -C "$W" -xf -
	find "$W" -name '*.o' -delete
	MK=Makefile.libretro; [ -f "$W/$MK" ] || MK=Makefile
	# the objects only (the core's own link step makes a .so we do not use);
	# no NTSC filter (floating point, software on the MT7688)
	make -C "$W" -f "$MK" -j8 platform=unix CC="$OUT/zcc" CXX="$OUT/zcxx" HAVE_NTSC=0 >"$OUT/retro-$CORE.log" 2>&1 || true
	OBJS=$(find "$W" -name '*.o' | sort)
	[ -n "$OBJS" ] || { tail -20 "$OUT/retro-$CORE.log"; exit 1; }
	rm -f "$OUT/libretro-$CORE.a"
	"$OUT/zar" rcs "$OUT/libretro-$CORE.a" $OBJS
	# linked as C++: some cores are (Gambatte)
	"$OUT/zcc" -O2 -c -DPSPEXP_RETRO_STATIC -D_REENTRANT -I"$P/include/SDL2" -include "$REN" \
		"$ROOT/tools/pspexp-retro/main.c" -o "$OUT/pspexp-retro.o"
	"$OUT/zcxx" -O2 -static "$OUT/pspexp-retro.o" "$OUT/libretro-$CORE.a" $LIBS "$P/lib/libSDL2.a" -lm \
		-o "$OUT/bin/pspexp-retro-$CORE" 2>"$OUT/retro-link.log" || { head -30 "$OUT/retro-link.log"; exit 1; }
fi
if [ "$1" = "tyrian" ]; then
	P="$OUT/prefix"
	[ -f "$P/lib/libSDL2.a" ] || "$ROOT/scripts/omega/build.sh" doom
	SRC="$ROOT/../tyrian/opentyrian"
	[ -f "$SRC/Makefile" ] || { echo "OpenTyrian source not found in $SRC (git clone https://github.com/opentyrian/opentyrian)" >&2; exit 1; }
	shim_static
	W="$OUT/src/opentyrian"
	rm -rf "$W"; mkdir -p "$W"
	{ COPYFILE_DISABLE=1 tar --no-xattrs -C "$SRC" --exclude .git --exclude obj --exclude opentyrian -cf - . ; } 2>/dev/null | tar -C "$W" -xf -
	# audio mixed at 11 kHz, not 44.1: its AdLib music emulation is double
	# floating point, emulated in software on the FPU-less MT7688 (the whole
	# CPU at 44.1 kHz: 14-23 fps and crackling sound); the SDL layer
	# upsamples 11025 Hz to the PSP's 44.1 kHz with integers
	sed -i.bak 's/^#define OUTPUT_QUALITY 4 .*/#define OUTPUT_QUALITY 1  \/\/ 11025 Hz (PSPExp, Omega2)/' "$W/src/loudness.c"
	grep -q '^#define OUTPUT_QUALITY 1 ' "$W/src/loudness.c" || { echo "OpenTyrian: OUTPUT_QUALITY not found in src/loudness.c" >&2; exit 1; }
	# every source sees the rename header; libc headers first (the generic
	# SDL_config.h includes none); network off (no SDL_net needed)
	make -C "$W" -j8 CC="$OUT/zcc" WITH_NETWORK=false \
		SDL_CPPFLAGS="-I$P/include/SDL2 -D_REENTRANT -include stdlib.h -include string.h -include math.h -include stdio.h -include $REN" \
		SDL_LDFLAGS="-static" SDL_LDLIBS="$LIBS $P/lib/libSDL2.a -lm" > "$OUT/tyrian.log" 2>&1 || { grep -E "error" "$OUT/tyrian.log" | head -20; exit 1; }
	cp "$W/opentyrian" "$OUT/bin/opentyrian"
fi
if [ "$1" = "cavestory" ]; then
	# Cave Story (NXEngine-evo, scripts/packages/build-nxengine.sh): static, the
	# SDL layer built in; every source sees the rename header, as for Tyrian
	P="$OUT/prefix"
	[ -f "$P/lib/libSDL2.a" ] || "$ROOT/scripts/omega/build.sh" doom
	shim_static
	W="$OUT/nxengine" CC="$OUT/zcc" CXX="$OUT/zcxx" AR="$OUT/zar" SDLINC="$P/include/SDL2" CFLAGS_X="-include $REN" \
		OUTBIN="$OUT/bin/nxengine-evo" LINK="-static $LIBS $P/lib/libSDL2.a -lm" \
		"$ROOT/scripts/packages/build-nxengine.sh"
fi
if [ "$1" = "jazz" ]; then
	# Jazz Jackrabbit (OpenJazz, scripts/packages/build-openjazz.sh): static,
	# the SDL layer built in, every source seeing the rename header; music
	# mixed at 22050 Hz with linear interpolation and no effects (the default
	# 44.1 kHz spline + DSP starved the FPU-less CPU: stalls, broken sound),
	# as OpenJazz's own PSP port does; the SDL layer upsamples for the PSP
	P="$OUT/prefix"
	[ -f "$P/lib/libSDL2.a" ] || "$ROOT/scripts/omega/build.sh" doom
	shim_static
	W="$OUT/openjazz" CC="$OUT/zcc" CXX="$OUT/zcxx" AR="$OUT/zar" SDLINC="$P/include/SDL2" \
		CFLAGS_X="-include $REN -DSOUND_FREQ=22050 -DMUSIC_SETTINGS=1" \
		OUTBIN="$OUT/bin/openjazz" LINK="-static $LIBS $P/lib/libSDL2.a -lm" \
		"$ROOT/scripts/packages/build-openjazz.sh"
fi
ls -la "$OUT/bin"
echo "static $ZIG_TARGET ($ZIG_CPU) binaries in build/$CROSS_NAME/bin"
