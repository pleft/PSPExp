static int oled_cmds(const uint8_t *c, size_t n)
{
    uint8_t buf[32];
    if (n > sizeof(buf) - 1) return -1;
    buf[0] = 0x00;   /* control byte: commands follow */
    memcpy(buf + 1, c, n);
    return write(g_fd, buf, n + 1) == (ssize_t)(n + 1) ? 0 : -1;
}

int oled_open(const char *dev)
{
#ifdef __linux__
    static const uint8_t init[] = {
        0xAE,             /* display off */
        0xD5, 0x80,       /* clock */
        0xA8, 0x3F,       /* multiplex 64 */
        0xD3, 0x00,       /* offset */
        0x40,             /* start line 0 */
        0x8D, 0x14,       /* charge pump on */
        0x20, 0x00,       /* horizontal addressing */
        0xA1, 0xC8,       /* segment remap, COM scan descending (right way up) */
        0xDA, 0x12,       /* COM pins */
        0x81, 0x8F,       /* contrast */
        0xD9, 0xF1,       /* precharge */
        0xDB, 0x40,       /* VCOM detect */
        0xA4, 0xA6,       /* follow RAM, normal (not inverted) */
        0xAF,             /* display on */
    };
    g_fd = open(dev ? dev : "/dev/i2c-0", O_RDWR);
    if (g_fd < 0) return -1;
    {
        long addr = getenv("PSPEXP_OLED_ADDR") ? strtol(getenv("PSPEXP_OLED_ADDR"), NULL, 0) : 0x3C;
        if (ioctl(g_fd, I2C_SLAVE, addr) < 0 || oled_cmds(init, sizeof(init)) < 0) { close(g_fd); g_fd = -1; return -1; }
    }
    memset(g_shown, 0x01, sizeof(g_shown));   /* nothing shown yet: the first flush draws */
    return 0;
#else
    (void)dev;
    return -1;
#endif
}

int oled_active(void) { return g_fd >= 0; }

void oled_line(int row, const char *text)
{
    if (row < 0 || row >= OLED_LINES) return;
    snprintf(g_lines[row], sizeof(g_lines[row]), "%-*.*s", OLED_COLS, OLED_COLS, text ? text : "");
}

void oled_flush(void)
{
    static const uint8_t window[] = { 0x21, 0, OLED_W - 1, 0x22, 0, OLED_PAGES - 1 };
    int r, i, p;
    if (g_fd < 0 || !memcmp(g_lines, g_shown, sizeof(g_lines))) return;
    memset(g_fb, 0, sizeof(g_fb));
    for (r = 0; r < OLED_LINES; r++)
        for (i = 0; i < OLED_COLS && g_lines[r][i]; i++) {
            unsigned char c = (unsigned char)g_lines[r][i];
            const uint8_t *g = FONT[(c >= 32 && c < 127) ? c - 32 : '?' - 32];
            memcpy(&g_fb[r][i * 6 + 1], g, 5);   /* 6 px a character: 21 in 128 */
        }
    if (oled_cmds(window, sizeof(window)) < 0) { oled_gone(); return; }
    for (p = 0; p < OLED_PAGES; p++) {
        uint8_t buf[1 + OLED_W];
        buf[0] = 0x40;   /* control byte: data follows */
        memcpy(buf + 1, g_fb[p], OLED_W);
        if (write(g_fd, buf, sizeof(buf)) != (ssize_t)sizeof(buf)) { oled_gone(); return; }
    }
    memcpy(g_shown, g_lines, sizeof(g_lines));
}

void oled_close(void)
{
    static const uint8_t off[] = { 0xAE };
    if (g_fd < 0) return;
    oled_cmds(off, sizeof(off));
    close(g_fd);
    g_fd = -1;
}
