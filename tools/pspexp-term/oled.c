/*
 * A small status panel on an SSD1306 128x64 OLED over I2C (the Onion OLED
 * Expansion on an Omega2+: /dev/i2c-0, address 0x3C). Eight lines of 21
 * characters in a 5x7 font; the whole screen is rewritten (1 KB) when its
 * text changes, at most every 2 s, so it costs a game nothing.
 *
 * Optional in every way: no bus, no display answering at start, or a write
 * failing later (unplugged) turns it off for good, quietly; the console goes
 * on as before. I2C writes to an absent device fail at once (no ACK), they
 * do not wait. PSPEXP_OLED_ADDR=0x3D for a display at the other address.
 */
#include <stdlib.h>
#include "oled.h"
#include <stdio.h>
#include <string.h>
#include <fcntl.h>
#include <unistd.h>
#ifdef __linux__
#include <sys/ioctl.h>
#include <linux/i2c-dev.h>
#endif

#define OLED_W 128
#define OLED_PAGES 8

static int g_fd = -1;
static uint8_t g_fb[OLED_PAGES][OLED_W];
static char g_lines[OLED_LINES][OLED_COLS + 1], g_shown[OLED_LINES][OLED_COLS + 1];

/* a write failed: the display is gone; stop using it */
static void oled_gone(void)
{
    if (g_fd >= 0) { close(g_fd); g_fd = -1; fprintf(stderr, "[oled] no answer: the status display is off\n"); }
}

